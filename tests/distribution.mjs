import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve } from 'node:path';
import { createDistribution, repository, validateModules, verifyDistribution } from '../scripts/distribution.mjs';
import { createConsumerProject, verifyConsumerModules } from '../scripts/consumer-project.mjs';
const parent = join(repository, '.impeccable/review');
mkdirSync(parent, { recursive: true });
const scratch = mkdtempSync(join(parent, 'distribution-test-'));
try {
  const pack = createDistribution(repository, scratch);
  const manifest = verifyDistribution(pack);
  assert.equal(manifest.components, 88);
  assert(manifest.files.length > 100);
  assert(!manifest.files.some(f => /(?:project\.config|node_modules|^pages\/|\.env)/.test(f.path)));
  const fixture = createConsumerProject(pack, scratch);
  assert(!existsSync(join(fixture, 'node_modules')));
  assert(!existsSync(join(fixture, 'components')));
  assert.equal(readFileSync(join(fixture, 'uni_modules/mori-ui/theme.uts'), 'utf8'), readFileSync(join(pack, 'uni_modules/mori-ui/theme.uts'), 'utf8'));
  verifyConsumerModules(pack, fixture);
  // Source edits must never be hidden by a complete but stale consumer copy.
  const removed = join(pack, 'uni_modules/mori-ui/static/icons/check-dark.svg');
  const removedBytes = readFileSync(removed);
  rmSync(removed);
  assert.throws(() => verifyConsumerModules(pack, fixture), /stale consumer file list/);
  writeFileSync(removed, removedBytes);
  const added = join(pack, 'uni_modules/mori-ui/static/icons/new-check.svg');
  writeFileSync(added, removedBytes);
  assert.throws(() => verifyConsumerModules(pack, fixture), /stale consumer file list/);
  rmSync(added);
  writeFileSync(removed, Buffer.concat([removedBytes, Buffer.from('\n<!-- changed -->')]));
  assert.throws(() => verifyConsumerModules(pack, fixture), /stale consumer code/);
  writeFileSync(removed, removedBytes);
  const guide = join(pack, 'uni_modules/mori-ui/README.md');
  const guideBytes = readFileSync(guide);
  writeFileSync(guide, Buffer.concat([guideBytes, Buffer.from('\nDocumentation only.\n')]));
  verifyConsumerModules(pack, fixture);
  writeFileSync(guide, guideBytes);
  const target = join(pack, 'uni_modules/mori-ui/theme.uts');
  const original = readFileSync(target);
  writeFileSync(target, Buffer.concat([original, Buffer.from('\n// changed')]));
  assert.throws(() => verifyDistribution(pack), /Changed size|Changed content/);
  writeFileSync(target, original);
  writeFileSync(target, "import { missing } from '../../outside.uts'\n");
  assert.throws(() => validateModules(pack), /escapes/);
  writeFileSync(target, original);
  const secret = join(pack, 'uni_modules/mori-ui/.env');
  writeFileSync(secret, 'SAMPLE=not-a-secret');
  assert.throws(() => validateModules(pack), /private\/cache/);
  rmSync(secret);
  const missing = join(pack, 'uni_modules/mori-ui/static/icons/check-dark.svg');
  const image = readFileSync(missing);
  rmSync(missing);
  assert.throws(() => verifyDistribution(pack), /ENOENT|Missing/);
  writeFileSync(missing, image);
  const meta = join(pack, 'uni_modules/mori-upload-ios/package.json');
  const originalMeta = readFileSync(meta, 'utf8');
  writeFileSync(meta, JSON.stringify({ ...JSON.parse(originalMeta), version: '9.9.9' }));
  assert.throws(() => validateModules(pack), /same distribution version/);
  writeFileSync(meta, originalMeta);
  verifyDistribution(pack);
  console.log('PASS distribution closure, integrity, independent scaffold and reuse rejection for deleted/added/modified runtime files; documentation-only edits remain reusable.');
} finally {
  const within = relative(resolve(parent), resolve(scratch));
  assert(within && !within.startsWith('..') && !isAbsolute(within), 'Cleanup must stay in the review directory.');
  rmSync(scratch, { recursive: true, force: true });
}
