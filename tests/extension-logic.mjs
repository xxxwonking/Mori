import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const root = new URL('../uni_modules/mori-ui/', import.meta.url);
function moduleUrl(path) {
  const url = new URL(path, root);
  let code = stripTypeScriptTypes(readFileSync(url, 'utf8'));
  code = code.replace(/from ['"](.+\.uts)['"]/g, (_, dependency) => 'from ' + JSON.stringify(moduleUrl(new URL(dependency, url).href)));
  return 'data:text/javascript;base64,' + Buffer.from(code).toString('base64');
}
const number = await import(moduleUrl('numeric.uts'));
assert.equal(number.snapMoriNumber(0.30000000000000004, 0, 1, 0.1), 0.3);
assert.equal(number.snapMoriNumber(999, 0, 5, 2), 5);
assert.equal(number.clampMoriNumber(NaN, 1, 10), 1);
assert.equal(number.moriPageCount(96, 10), 10);
assert.equal(number.moriPageCount(-1, 0), 1);
assert.deepEqual(number.moriPageItems(10, 10, 5), [6, 7, 8, 9, 10]);
assert.deepEqual(number.moriPageItems(1, 3, 5), [1, 2, 3]);
const calendar = await import(moduleUrl('calendar.uts'));
assert.equal(calendar.parseMoriDate('2025-02-29'), null);
assert.equal(calendar.parseMoriDate('2026-13-01'), null);
assert.equal(calendar.parseMoriDate('26-01-01'), null);
assert.equal(calendar.formatMoriDate(calendar.parseMoriDate('2024-02-29')), '2024-02-29');
assert.deepEqual(calendar.selectMoriDate([], '2026-10-15', 'single', '', '', [], 0), ['2026-10-15']);
assert.deepEqual(calendar.selectMoriDate(['2026-10-15'], '2026-10-15', 'multiple', '', '', [], 0), []);
assert.deepEqual(calendar.selectMoriDate(['2026-10-15'], '2026-10-14', 'range', '', '', [], 7), ['2026-10-14']);
assert.equal(calendar.selectMoriDate(['2026-10-15'], '2026-10-22', 'range', '', '', [], 7), null);
assert.deepEqual(calendar.selectMoriDate(['2026-10-15'], '2026-10-21', 'range', '', '', [], 7), ['2026-10-15', '2026-10-21']);
assert.equal(calendar.selectMoriDate(['2026-10-15'], '2026-10-19', 'range', '', '', ['2026-10-18'], 0), null);
assert.equal(calendar.selectMoriDate([], '2026-10-15', 'single', '2026-10-16', '', [], 0), null);
assert.equal(calendar.validMoriCalendarValue(['2026-10-15'], 'range', '', '', [], 0), false);
assert.equal(calendar.validMoriCalendarValue(['2026-10-15', '2026-10-14'], 'range', '', '', [], 0), false);
assert.equal(calendar.validMoriCalendarValue(['2026-10-15','2026-10-20'], 'range', '', '', ['2026-10-18'], 0), false);
const dt = await import(moduleUrl('datetime.uts'));
assert.equal(dt.validMoriDateTime('2024-02-29 23:59', 'datetime'), true);
assert.equal(dt.validMoriDateTime('2024-02-29 24:00', 'datetime'), false);
assert.equal(dt.validMoriTime('09:60'), false);
assert.equal(dt.moriDateTimeAllowed('2026-10-30 08:00','datetime','2026-10-30 09:00',''), false);
assert.equal(dt.initialMoriDateTime('','time','10:00','18:00'), '10:00');
const upload = await import(moduleUrl('upload.uts'));
assert.equal(upload.moriUploadCapacity(3, 2), 0);
assert.equal(upload.moriUploadFileIssue({path:'/tmp/a.heic',size:50},100), '');
assert.equal(upload.moriUploadFileIssue({path:'/tmp/a.heic',size:101},100), '文件超过大小限制');
assert.equal(upload.moriUploadFileIssue({path:'',size:50},100), '文件路径为空');
const file = upload.createMoriUploadFile({path:'file:///私有目录/a%20b.heic',name:'a b.heic',size:50,type:''});
assert.equal(file.url, 'file:///私有目录/a%20b.heic', 'iOS paths remain opaque');
assert.notEqual(file.id, upload.createMoriUploadFile({path:'same',name:'same',size:0,type:''}).id);
assert.notEqual(upload.copyMoriUploadFile(file), file);
