import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const sourceUrl = new URL('../uni_modules/mori-ui/selection.uts', import.meta.url);
assert.ok(existsSync(sourceUrl), 'Selection behavior module is implemented');
const source = stripTypeScriptTypes(readFileSync(sourceUrl, 'utf8'));
const { selectMoriRadio, toggleMoriChoice, nextMoriChoiceIndex, limitMoriText } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
assert.equal(selectMoriRadio('a', 'b', false), 'b');
assert.equal(selectMoriRadio('a', 'a', false), null, 'Already-selected radio does not emit');
assert.equal(selectMoriRadio('a', 'b', true), null, 'Disabled radio cannot change');
const original = Object.freeze(['a']);
assert.deepEqual(toggleMoriChoice(original, 'b', false, 0, 2), ['a', 'b']);
assert.deepEqual(original, ['a'], 'Group never mutates the incoming model');
assert.deepEqual(toggleMoriChoice(original, 'a', false, 0, 2), []);
assert.equal(toggleMoriChoice(original, 'a', false, 1, 2), null, 'Minimum prevents removal');
assert.equal(toggleMoriChoice(original, 'b', false, 0, 1), null, 'Maximum prevents adding');
assert.equal(toggleMoriChoice(original, 'b', true, 0, 0), null, 'Disabled entry stays unchanged');
assert.deepEqual(toggleMoriChoice(['a', 'a'], 'b', false, 0, 0), ['a', 'b'], 'Next values are unique');
assert.deepEqual(toggleMoriChoice(['a', 'b', 'c'], 'c', false, 0, 2), ['a', 'b'], 'Existing oversized models can be reduced');
const options = [{label:'A', value:'a'}, {label:'B', value:'b', disabled:true}, {label:'C', value:'c'}];
assert.equal(nextMoriChoiceIndex(options, 'a', 1), 2);
assert.equal(nextMoriChoiceIndex(options, 'c', 1), 0);
assert.equal(nextMoriChoiceIndex(options, 'a', -1), 2);
assert.equal(nextMoriChoiceIndex([], '', 1), -1);
assert.equal(nextMoriChoiceIndex([{label:'A',value:'a',disabled:true}], '', 1), -1);
assert.equal(limitMoriText('abcdef', 3), 'abc');
assert.equal(limitMoriText('abcdef', -1), 'abcdef');
assert.equal(limitMoriText('abcdef', 0), '');
assert.equal(limitMoriText('说明\n第二行', 200), '说明\n第二行');
console.log('PASS selection exclusivity, immutable groups, bounds, disabled navigation and text limits');
