import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const file = new URL('../uni_modules/mori-ui/feedback.uts', import.meta.url);
assert.ok(existsSync(file), 'Toast timer controller must exist');
const source = stripTypeScriptTypes(readFileSync(file, 'utf8'));
const { createMoriToastTimer } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
let nextId = 0;
const jobs = new Map();
const canceled = [];
const timer = createMoriToastTimer((callback, delay) => { const id = ++nextId; jobs.set(id, {callback, delay}); return id; }, id => canceled.push(id));
let expired = 0;
timer.restart(100, () => expired++);
assert.equal(jobs.get(1).delay, 100);
timer.restart(200, () => expired++);
assert.deepEqual(canceled, [1]);
jobs.get(1).callback();
assert.equal(expired, 0, 'Replaced callbacks cannot close the current toast');
jobs.get(2).callback();
assert.equal(expired, 1);
jobs.get(2).callback();
assert.equal(expired, 1, 'Expiry executes at most once');
timer.restart(300, () => expired++);
timer.cancel();
timer.cancel();
jobs.get(3).callback();
assert.equal(expired, 1, 'Manual close invalidates pending callbacks');
timer.restart(0, () => expired++);
assert.equal(nextId, 3, 'Persistent notifications have no timer');
timer.restart(100, () => expired++);
timer.restart(0, () => expired++);
jobs.get(4).callback();
assert.equal(expired, 1, 'Replacing timed notification with persistent invalidates old timer');
timer.restart(100, () => expired++);
timer.dispose();
jobs.get(5).callback();
assert.equal(expired, 1, 'Unmount invalidates pending callbacks');
timer.restart(100, () => expired++);
assert.equal(nextId, 5, 'Disposed timer cannot schedule');
console.log('PASS toast timeout replacement, idempotent expiry, manual close, persistence and unmount');
