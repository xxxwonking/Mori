import { readFileSync, existsSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import assert from 'node:assert/strict';
const path = new URL('../uni_modules/mori-ui/overlay.uts', import.meta.url);
assert.ok(existsSync(path), 'Overlay lifecycle helpers must exist');
const source = stripTypeScriptTypes(readFileSync(path, 'utf8'));
const o = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
assert.equal(o.acquireMoriOverlay('outer', 5000), 5000);
assert.equal(o.acquireMoriOverlay('inner', 1000), 5002, 'Newest popup is above a larger custom z-index');
assert.equal(o.isTopMoriOverlay('inner'), true);
assert.equal(o.isTopMoriOverlay('outer'), false);
o.releaseMoriOverlay('outer');
assert.equal(o.isTopMoriOverlay('inner'), true, 'Non-top release preserves top');
assert.equal(o.acquireMoriOverlay('third', 8000), 8000);
o.releaseMoriOverlay('third');
assert.equal(o.isTopMoriOverlay('inner'), true);
assert.equal(o.acquireMoriOverlay('inner', 1000), 1000, 'Reversal does not duplicate stack ownership');
o.releaseMoriOverlay('inner');
assert.equal(o.topMoriOverlayId(), '');
o.releaseMoriOverlay('inner');
assert.equal(o.topMoriOverlayId(), '');
const gate = o.createMoriOverlayGate();
const opening = o.advanceMoriOverlayGate(gate);
const closing = o.advanceMoriOverlayGate(gate);
assert.equal(o.isCurrentMoriOverlayGate(gate, opening), false);
const reopened = o.advanceMoriOverlayGate(gate);
assert.equal(o.isCurrentMoriOverlayGate(gate, closing), false, 'Stale close cannot release reopened popup');
assert.equal(o.isCurrentMoriOverlayGate(gate, reopened), true);
o.advanceMoriOverlayGate(gate);
assert.equal(o.isCurrentMoriOverlayGate(gate, reopened), false, 'Unmount invalidates queued callbacks');
assert.equal(o.moriOverlayDuration(-1), 0);
assert.equal(o.moriOverlayDuration(180), 180);
assert.equal(o.moriOverlayDuration(NaN), 0);
console.log('PASS overlay stack, custom z-index, release order and transition cancellation');
