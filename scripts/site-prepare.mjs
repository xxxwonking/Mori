import { readFileSync, writeFileSync, mkdirSync, readdirSync, cpSync, existsSync } from 'node:fs';
import { resolve, dirname, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { componentManifest } from './component-manifest.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const write = (path, source) => { const file = resolve(root, path); mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, source); };
const content = resolve(root, 'site/.generated');
mkdirSync(content, { recursive: true });
// The Markdown in docs/ remains the source of truth. Never hand-edit .generated/.
function copyDocs(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name);
    if (entry.isDirectory()) { copyDocs(file); continue; }
    if (!entry.name.endsWith('.md')) continue;
    const target = relative(resolve(root, 'docs'), file).replaceAll('\\', '/');
    let source = readFileSync(file, 'utf8');
    source = source.replace(/\]\(([^)]+)\)/g, (match, href) => {
      if (/^(https?:|mailto:|#)/.test(href)) return match;
      const [path, anchor = ''] = href.split('#');
      const full = resolve(dirname(file), path);
      const repoPath = relative(root, full).replaceAll('\\', '/');
      if (!repoPath.startsWith('docs/')) return `](https://github.com/xxxwonking/Mori/blob/master/${repoPath}${anchor ? '#' + anchor : ''})`;
      return match;
    });
    const c = componentManifest.find(c => target === `components/${c.name}.md`);
    if (c) source = `---\ncomponent: ${c.name}\n---\n\n` + source.replace(/^# .+/, `# ${c.name.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join('')} ${c.title}`);
    write(`site/.generated/${target}`, source);
  }
}
copyDocs(resolve(root, 'docs'));
write('site/.generated/index.md', readFileSync(resolve(root, 'site/home.md'), 'utf8'));
mkdirSync(resolve(content, 'public'), { recursive: true });
cpSync(resolve(root, 'site/public'), resolve(content, 'public'), { recursive: true });
cpSync(resolve(root, 'docs/assets'), resolve(content, 'public/assets'), { recursive: true });
// Docs images use assets/ relative to a Markdown file, so retain their source paths too.
cpSync(resolve(root, 'docs/assets'), resolve(content, 'assets'), { recursive: true });

const rows = [];
for (const c of componentManifest) {
  const override = resolve(root, `site/demos/${c.name}.uvue`);
  let source = existsSync(override) ? readFileSync(override, 'utf8') : readFileSync(resolve(root, `docs/components/${c.name}.md`), 'utf8').match(/```vue\r?\n([\s\S]*?)```/)[1];
  source = source.replaceAll('/static/example.png', '/static/mori-demo.svg');
  // Real components run in the uni-app x build, isolated from the VitePress Vue runtime.
  const name = `site-demo-${c.name}`;
  write(`components/${name}/${name}.uvue`, `<!-- Generated by site-prepare.mjs from docs/components or site/demos. -->\n${source}`);
  rows.push(`    <${name} v-if="current == '${c.name}'" />`);
}
write('pages/preview/catalog.uts', `// Generated from component-manifest.mjs\nexport const previewItems = ${JSON.stringify(componentManifest)}\n`);
write('components/site-preview-content/site-preview-content.uvue', `<!-- Generated by site-prepare.mjs. -->\n<template>\n  <view class="site-preview-content">\n${rows.join('\n')}\n  </view>\n</template>\n<script setup lang="uts">\ndefineProps({ current: { type: String, default: 'button' } })\n</script>\n<style>\n.site-preview-content { display: flex; flex-direction: column; gap: 16px; }\n</style>\n`);
console.log(`Prepared ${componentManifest.length} docs and real .uvue demos.`);
