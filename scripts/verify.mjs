import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const out = new URL('../.impeccable/review/', import.meta.url);
mkdirSync(out, { recursive: true });
const baseURL = process.env.MORI_BASE_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chromium', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', reducedMotion: 'reduce' });
const errors = [];
const checks = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.status() >= 400) errors.push(response.status() + ' ' + response.url()); });
const check = async (name, task) => { await task(); checks.push(name); console.log('PASS ' + name); };
const nav = async name => { await page.locator('.sidebar .nav-item').filter({ hasText: name }).click(); };
const mode = async name => { await page.locator('.appearance-option').filter({ hasText: name }).click(); };
const capture = async name => {
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForLoadState('networkidle');
  await page.screenshot({ path: fileURLToPath(new URL(name, out)), fullPage: true });
};
try {
  await page.goto(baseURL, { waitUntil: 'networkidle' });
  await page.addStyleTag({ content: '*, *::before, *::after { transition: none !important; animation: none !important; }' });
  await check('Default auto follows light, then live system dark changes', async () => {
    await expect(page.locator('.appearance-option--active')).toHaveText('自动');
    await expect(page.locator('.workbench')).not.toHaveClass(/workbench--dark/);
    await page.emulateMedia({ colorScheme: 'dark' });
    await expect(page.locator('.workbench')).toHaveClass(/workbench--dark/);
    await expect(page.locator('.mori-field').first()).toHaveClass(/mori-field--dark/);
    await expect(page.locator('.button-stage .mori-button').first()).toHaveCSS('background-color', 'rgb(140, 182, 255)');
  });
  await check('Explicit light ignores system changes; auto resumes immediately', async () => {
    await mode('浅色');
    await expect(page.locator('.workbench')).not.toHaveClass(/workbench--dark/);
    await page.emulateMedia({ colorScheme: 'light' });
    await page.emulateMedia({ colorScheme: 'dark' });
    await expect(page.locator('.workbench')).not.toHaveClass(/workbench--dark/);
    await mode('自动');
    await expect(page.locator('.workbench')).toHaveClass(/workbench--dark/);
    await page.emulateMedia({ colorScheme: 'light' });
    await expect(page.locator('.workbench')).not.toHaveClass(/workbench--dark/);
  });
  await check('Explicit dark remains dark in a light system', async () => {
    await mode('深色');
    await expect(page.locator('.workbench')).toHaveClass(/workbench--dark/);
    await capture('desktop-dark.png');
    await mode('自动');
  });
  await check('Shared brand changes both specimen and composed form', async () => {
    await page.locator('.theme-swatch[aria-label="靛蓝主题"]').click();
    await expect(page.locator('.button-stage .mori-button').first()).toHaveCSS('background-color', 'rgb(70, 91, 163)');
    await expect(page.locator('.demo-form__submit .mori-button')).toHaveCSS('background-color', 'rgb(70, 91, 163)');
    await page.locator('.theme-swatch[aria-label="清晰蓝主题"]').click();
  });
  await check('Button click, keyboard, size, loading and disabled behavior', async () => {
    const button = page.locator('.button-stage .mori-button').first();
    await button.click();
    await expect(page.locator('.stage-result')).toHaveText('主要按钮已点击');
    await button.focus();
    await button.press('Enter');
    await page.locator('.size-option').filter({ hasText: '大' }).click();
    await expect(button).toHaveCSS('height', '40px');
    await page.locator('.stage-setting').filter({ hasText: '加载中' }).locator('[role="switch"]').click();
    await expect(button).toHaveAttribute('aria-busy', 'true');
    await expect(button).toHaveAttribute('aria-disabled', 'true');
    await page.locator('.stage-setting').filter({ hasText: '加载中' }).locator('[role="switch"]').click();
    await page.locator('.stage-setting').filter({ hasText: '禁用状态' }).locator('[role="switch"]').click();
    await expect(button).toHaveAttribute('aria-disabled', 'true');
    await page.locator('.stage-setting').filter({ hasText: '禁用状态' }).locator('[role="switch"]').click();
    await page.locator('.size-option').filter({ hasText: '中' }).click();
  });
  await check('Composed form validates, saves locally and resets', async () => {
    const form = page.locator('.demo-form');
    await form.locator('.demo-form__submit .mori-button').click();
    await expect(form.getByText('请填写你的名字', { exact: true })).toBeVisible();
    await expect(form.getByText('请填写电子邮箱', { exact: true })).toBeVisible();
    await form.locator('input').nth(0).fill('Mori');
    await form.locator('input').nth(1).fill('invalid-email');
    await expect(form.getByText('邮箱格式不正确，例如 name@example.com')).toBeVisible();
    await expect(form.locator('input').nth(1)).toHaveAttribute('aria-required', 'true');
    await expect(form.locator('input').nth(1)).toHaveAttribute('aria-invalid', 'true');
    const descriptionId = await form.locator('input').nth(1).getAttribute('aria-describedby');
    await expect(page.locator('[id="' + descriptionId + '"]')).toContainText('邮箱格式不正确');
    await expect(form.locator('.mori-field__control--focused')).toHaveCSS('outline-style', 'none');
    await expect(form.locator('.mori-field__control--focused')).toHaveCSS('border-color', 'rgb(0, 102, 214)');
    await capture('desktop-form-error.png');
    await form.locator('input').nth(1).fill('mori@example.com');
    await form.locator('[role="checkbox"]').click();
    await form.locator('.demo-form__submit .mori-button').click();
    await expect(form.locator('.demo-form__success')).toContainText('已保存');
    await form.locator('.demo-form__reset').click();
    await expect(form.locator('input').nth(0)).toHaveValue('');
    await expect(form.locator('input').nth(1)).toHaveValue('');
    await expect(form.locator('.demo-form__success')).toHaveCount(0);
  });
  await check('Input v-model, clear, validation, password reveal and disabled field', async () => {
    await nav('Input');
    const inputs = page.locator('.input-stage input');
    await inputs.nth(0).fill('组件测试');
    await page.locator('.input-stage').getByRole('button', { name: '清空输入' }).first().click();
    await expect(inputs.nth(0)).toHaveValue('');
    await inputs.nth(1).fill('name@example.com');
    await expect(page.locator('.input-stage .mori-field__message--error')).toHaveCount(0);
    await expect(inputs.nth(2)).toHaveAttribute('type', 'password');
    await page.locator('.input-stage').getByRole('button', { name: '显示密码' }).click();
    await expect(inputs.nth(2)).toHaveAttribute('type', 'text');
    await expect(inputs.nth(3)).toBeDisabled();
    const passwordField = page.locator('.input-stage .mori-field').nth(2);
    await expect(passwordField.locator('.mori-field__action')).toHaveCount(2);
    await expect(passwordField.locator('.mori-field__action')).toHaveText(['', '']);
    await passwordField.getByRole('button', { name: '隐藏密码' }).focus();
    await passwordField.getByRole('button', { name: '隐藏密码' }).press('Enter');
    await expect(inputs.nth(2)).toHaveAttribute('type', 'password');
    await inputs.nth(2).focus();
    const initialBounds = await passwordField.locator('.mori-field__control').boundingBox();
    await expect(passwordField.locator('.mori-field__control')).toHaveCSS('height', '36px');
    await expect(passwordField.locator('.mori-field__control')).toHaveCSS('border-width', '1px');
    await expect(passwordField.locator('.mori-field__control')).toHaveCSS('outline-style', 'none');
    await expect(inputs.nth(2)).toHaveCSS('outline-style', 'none');
    await passwordField.getByRole('button', { name: '显示密码' }).click();
    await expect(inputs.nth(2)).toBeFocused();
    expect(await passwordField.locator('.mori-field__control').boundingBox()).toEqual(initialBounds);
    await capture('desktop-input.png');
    await mode('深色');
    await inputs.nth(1).fill('invalid-email');
    await expect(page.locator('.input-stage .mori-field__control--focused')).toHaveCSS('border-color', 'rgb(140, 182, 255)');
    await capture('desktop-input-dark.png');
    await inputs.nth(1).fill('name@example.com');
    await mode('自动');
  });
  await check('Switch, checkbox and API navigation', async () => {
    await nav('Switch');
    const switcher = page.locator('.selection-stage [role="switch"]').first();
    await expect(switcher).toHaveAttribute('aria-checked', 'true');
    await switcher.click();
    await expect(switcher).toHaveAttribute('aria-checked', 'false');
    await switcher.focus();
    await switcher.press('Space');
    await expect(switcher).toHaveAttribute('aria-checked', 'true');
    const withText = page.locator('.selection-stage [role="switch"]').nth(1);
    await expect(withText.locator('.mori-switch__state')).toHaveText('关');
    await withText.click();
    await expect(withText).toHaveAttribute('aria-checked', 'true');
    await expect(withText.locator('.mori-switch__state')).toHaveText('开');
    const locked = page.locator('.selection-stage [role="switch"]').nth(2);
    await locked.click({ force: true });
    await expect(locked).toHaveAttribute('aria-checked', 'true');
    await expect(locked).toHaveAttribute('tabindex', '-1');
    const colors = page.locator('.switch-color-example');
    const green = colors.nth(0);
    await expect(green.locator('.mori-switch__track')).toHaveCSS('background-color', 'rgb(35, 134, 83)');
    await green.getByRole('switch').click();
    await expect(green.locator('.mori-switch__track')).toHaveCSS('background-color', 'rgb(220, 233, 225)');
    await expect(green.locator('.mori-switch__state')).toHaveText('OFF');
    await green.getByRole('switch').press('Space');
    await expect(green.locator('.mori-switch__state')).toHaveText('ON');
    const twoTone = colors.nth(3);
    await expect(twoTone.locator('.mori-switch__track')).toHaveCSS('background-color', 'rgb(182, 61, 55)');
    for (const item of await colors.all()) {
      const textBox = await item.locator('.mori-switch__state').boundingBox();
      const thumb = await item.locator('.mori-switch__thumb').boundingBox();
      expect(textBox.x + textBox.width <= thumb.x + 0.5 || textBox.x >= thumb.x + thumb.width - 0.5).toBe(true);
    }
    const heights = await page.locator('.switch-size-example .mori-switch__track').evaluateAll(els => els.map(el => getComputedStyle(el).height));
    expect(heights).toEqual(['20px','22px','26px']);
    await capture('desktop-switch.png');
    await mode('深色');
    await expect(green.locator('.mori-switch__track')).toHaveCSS('background-color', 'rgb(35, 134, 83)');
    await expect(switcher.locator('.mori-switch__track')).toHaveCSS('background-color', 'rgb(140, 182, 255)');
    await capture('desktop-switch-dark.png');
    await mode('自动');
    await nav('Checkbox');
    await page.locator('.selection-stage [role="checkbox"]').nth(1).click();
    await expect(page.locator('.selection-summary-text')).toContainText('2');
    const checkboxes = page.locator('.selection-stage [role="checkbox"]');
    await expect(checkboxes.first().locator('.mori-checkbox__box')).toHaveCSS('background-color', 'rgb(0, 102, 214)');
    await expect(checkboxes.first().locator('.mori-checkbox__box')).toHaveCSS('width', '16px');
    await checkboxes.nth(1).locator('.mori-checkbox__label').click();
    await expect(page.locator('.selection-summary-text')).toContainText('1');
    await checkboxes.nth(1).focus();
    await checkboxes.nth(1).press('Space');
    await expect(page.locator('.selection-summary-text')).toContainText('2');
    await checkboxes.nth(2).click({ force: true });
    await expect(checkboxes.nth(2)).toHaveAttribute('aria-checked', 'true');
    await checkboxes.nth(3).click({ force: true });
    await expect(checkboxes.nth(3)).toHaveAttribute('aria-checked', 'false');
    await page.locator('.page-title').click();
    await capture('desktop-checkbox.png');
    await mode('深色');
    await expect(checkboxes.first().locator('.mori-checkbox__box')).toHaveCSS('background-color', 'rgb(140, 182, 255)');
    await capture('desktop-checkbox-dark.png');
    await mode('自动');
    await page.locator('.section-tab').filter({ hasText: 'API 参考' }).click();
    await expect(page.locator('.api-panel')).toContainText('v-model');
    await page.locator('.guide-link').click();
    await expect(page.locator('.guide-content')).toContainText('setMoriConfig');
    await expect(page.locator('.guide-content')).toContainText('initMoriTheme');
    await expect(page.locator('.guide-content')).toContainText('darkmode');
    await nav('Button');
  });
  await check('Responsive layouts have no horizontal overflow', async () => {
    for (const width of [360, 390, 768, 1024, 1280, 1440]) {
      await page.setViewportSize({ width, height: width < 640 ? 844 : 1000 });
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
      expect(overflow, 'Overflow at ' + width).toBe(false);
      if (width === 1440) await capture('desktop.png');
      if (width === 390) {
        await capture('mobile.png');
        await mode('深色');
        await capture('mobile-dark.png');
        await mode('自动');
        await page.locator('.mobile-nav-item').filter({ hasText: '输入框' }).click();
        await page.locator('.input-stage input').nth(2).focus();
        await capture('mobile-input.png');
        await page.locator('.mobile-nav-item').filter({ hasText: '开关' }).click();
        await capture('mobile-switch.png');
        expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
        await page.locator('.mobile-nav-item').filter({ hasText: '按钮' }).click();
      }
    }
  });
  expect(errors).toEqual([]);
  const result = { passed: checks.length, checks, errors, browser: browser.version(), generated: new Date().toISOString() };
  writeFileSync(new URL('verification.json', out), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
