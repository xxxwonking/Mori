import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';

const browser = await chromium.launch({ channel: process.env.MORI_BROWSER_EXECUTABLE ? undefined : 'chromium', executablePath: process.env.MORI_BROWSER_EXECUTABLE || undefined, headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 960 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const out = new URL('../.impeccable/review/', import.meta.url);
mkdirSync(out, { recursive: true });
try {
  await page.goto((process.env.MORI_BASE_URL || 'http://127.0.0.1:5173') + '/#/pages/forms/forms');
  await expect(page.getByText('表单基础', { exact: true }).first()).toBeVisible();
  const form = page.locator('.foundation-form');
  await page.getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(form.getByText('请填写称呼', { exact: true })).toBeVisible();
  await expect(form.getByText('请选择身份', { exact: true })).toBeVisible();
  const initialBio = form.locator('textarea');
  await expect(initialBio).toHaveAttribute('aria-invalid', 'true');
  const bioErrorId = await initialBio.getAttribute('aria-describedby');
  expect(bioErrorId).toBeTruthy();
  await expect(page.locator('[id="' + bioErrorId + '"]')).toHaveText('请填写个人介绍');
  await expect(form.getByRole('radiogroup', { name: '身份' })).toHaveAttribute('aria-invalid', 'true');
  const name = form.locator('input');
  await expect(name).toHaveAttribute('aria-label', '称呼');
  await expect(name).toHaveAttribute('aria-invalid', 'true');
  const messageId = await name.getAttribute('aria-describedby');
  expect(messageId).toBeTruthy();
  await expect(page.locator('[id="' + messageId + '"]')).toHaveText('请填写称呼');
  await name.fill('Mori');
  await name.blur();
  await expect(name).toHaveAttribute('aria-invalid', 'false');
  await expect(form.getByText('请选择身份', { exact: true })).toBeVisible();
  const radio = form.getByRole('radio', { name: '设计师', exact: true });
  await radio.click();
  await expect(radio).toHaveAttribute('aria-checked', 'true');
  await form.getByRole('radio', { name: '开发者', exact: true }).click();
  await expect(radio).toHaveAttribute('aria-checked', 'false');
  await form.getByRole('radio', { name: '暂不可选', exact: true }).click({ force: true });
  await expect(form.getByRole('radio', { name: '开发者', exact: true })).toHaveAttribute('aria-checked', 'true');
  await form.getByRole('radio', { name: '开发者', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(radio).toHaveAttribute('aria-checked', 'true');
  await expect(radio).toBeFocused();
  await form.getByRole('checkbox', { name: '界面设计', exact: true }).click();
  await form.getByRole('checkbox', { name: '交互体验', exact: true }).click();
  await form.getByRole('checkbox', { name: '工程实践', exact: true }).click({ force: true });
  await expect(form.getByRole('checkbox', { name: '工程实践', exact: true })).toHaveAttribute('aria-checked', 'false');
  await expect(form.getByRole('checkbox', { name: '即将开放', exact: true })).toHaveAttribute('aria-disabled', 'true');
  const bio = form.locator('textarea');
  await expect(bio).toHaveAttribute('aria-label', '个人介绍');
  await bio.fill('我正在构建自己的移动组件库。');
  await bio.blur();
  await expect(bio).toHaveAttribute('aria-invalid', 'false');
  await page.getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(page.getByText('校验通过，资料已在本页保存。', { exact: true })).toBeVisible();
  await bio.fill('a'.repeat(130));
  await expect(bio).toHaveValue('a'.repeat(120));
  await expect(form.getByText('120 / 120', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '重置示例', exact: true }).click();
  await expect(name).toHaveValue('');
  await expect(name).toHaveAttribute('aria-invalid', 'false');
  await expect(form.getByRole('radio', { checked: true })).toHaveCount(0);
  await expect(form.getByRole('checkbox', { checked: true })).toHaveCount(0);
  await page.getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(name).toHaveAttribute('aria-invalid', 'true');
  await page.getByRole('button', { name: '重置示例', exact: true }).click();
  await expect(name).toHaveAttribute('aria-invalid', 'false');
  await expect(form.getByText('请填写称呼', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: new URL('forms-desktop-light.png', out).pathname, fullPage: true });
  await page.getByRole('button', { name: '深色', exact: true }).click();
  await expect(page.locator('.forms-page')).toHaveClass(/forms-page--dark/);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(form.locator('.mori-textarea__control')).toHaveCSS('background-color', 'rgb(28, 32, 40)');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: new URL('forms-mobile-dark.png', out).pathname });
  await page.getByRole('button', { name: '保存资料', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: new URL('forms-mobile-dark-submit.png', out).pathname });
  await page.setViewportSize({ width: 360, height: 780 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('.disabled-examples textarea')).toBeDisabled();
  expect(errors).toEqual([]);
  writeFileSync(new URL('forms-verification.json', out), JSON.stringify({ generated: new Date().toISOString(), browser: browser.version(), passed: true, errors, checks: ['required and field accessibility', 'field correction preserves other errors', 'exclusive radio and disabled option', 'checkbox max and disabled option', 'textarea value and limit', 'successful local submit', 'reset clears state', 'dark mobile no overflow', 'disabled textarea'] }, null, 2));
  console.log('PASS form foundations: validation, context, selection, textarea, reset, dark/mobile');
} finally { await browser.close(); }
